"""Discovery batch: generate -> pre-register -> event-study screen -> full evaluation, in parallel.

    uv run python scripts/discovery.py D5-01 --register   # pre-register every idea, then COMMIT
    uv run python scripts/discovery.py D5-01              # run the batch (resumable)

Stages and what each controls (docs/DISCOVERY.md):
  1. Generation. Every (entry, trend filter, exit) rule x instrument is a hypothesis; the rule
     combination is its *family*, so the same rule on 17 instruments shares one trial count.
  2. Event study (development data). Does the entry condition predict better-than-normal returns?
     Benjamini-Hochberg across every test in the batch; survivors become EFFECT, the rest REJECTED.
  3. Full evaluation (lab.validation.evaluate) of EFFECT hypotheses: grid search with every config a
     trial, 2x costs, Deflated Sharpe with the family's full planned trial count, PBO, SPA,
     walk-forward, plateau, yearly consistency, then one validation look. Runs on all CPU cores.
  The vault is never touched here; promotion to VALIDATED stays a separate, once-only step.
"""

from __future__ import annotations

import json
import math
import os
import time
from concurrent.futures import ProcessPoolExecutor, as_completed
from dataclasses import asdict
from pathlib import Path

import numpy as np

from lab import instruments
from lab.discovery import screen
from lab.discovery import templates as T
from lab.engine.backtest import ExecutionConfig, RiskConfig
from lab.engine.data import load
from lab.registry.db import Registry
from lab.validation import stats

ROOT = Path(__file__).resolve().parents[3]
OUT = ROOT / "research" / "discovery"
REPORTS = ROOT / "reports" / "discovery"

EQUITY = ["SPY", "QQQ", "IWM", "DIA", "TLT", "GLD", "XLK", "XLF", "XLE", "XLV", "XLY", "XLP", "XLI", "XLU"]
CRYPTO = ["BTCUSDT", "ETHUSDT", "SOLUSDT"]
UNIVERSE = EQUITY + CRYPTO
TIMEFRAME = "1d"
FDR_Q = 0.05
RISK = {"sizing": "pct_equity", "position_pct": 1.0}


def cost_profile(symbol: str) -> str | None:
    # Crypto at US-accessible retail costs (D-010): the owner's account is US-based.
    return "crypto_spot_us_retail" if instruments.get(symbol).asset_class == "crypto" else None


def specs(batch: str, universe=UNIVERSE) -> list[dict]:
    """Deterministic list of every hypothesis in the batch."""
    out, n = [], 0
    for entry, e in T.ENTRIES.items():
        for filt in T.FILTERS:
            for ex in e.exits:
                for sym in universe:
                    n += 1
                    x = T.EXITS[ex]
                    out.append({
                        "id": f"{batch}-{n:04d}", "entry": entry, "filter": filt, "exit": ex, "symbol": sym,
                        "family": f"disc:{entry}:{filt}:{ex}",
                        "space": {"x": list(e.grid), "y": list(x.grid)},
                        "title": f"{sym}: {e.describe}; {T.FILTERS[filt]}; {x.describe}",
                    })
    return out


def register(batch: str, reg: Registry, universe=UNIVERSE) -> list[dict]:
    hs = specs(batch, universe)
    for h in hs:
        e = T.ENTRIES[h["entry"]]
        cls = T.rule_strategy(h["entry"], h["filter"], h["exit"])
        reg.register_hypothesis(
            id=h["id"], family=h["family"], title=h["title"], source=f"discovery:{batch}",
            question=f"On {h['symbol']} daily bars, does going long when {e.describe} ({T.FILTERS[h['filter']]}) "
                     f"and {T.EXITS[h['exit']].describe} make money after costs?",
            rationale=f"Generated by the discovery engine: {e.style} template, screened first by an event study "
                      f"(next-open to {T.HORIZON[e.style]}-bar return vs normal, BH FDR {FDR_Q} across the batch).",
            asset_classes=[instruments.get(h["symbol"]).asset_class], instruments=[h["symbol"]],
            timeframe=TIMEFRAME, style=e.style,
            spec={"strategy": cls.name, "strategy_version": cls().strategy_version, "fixed": {},
                  "profile": cost_profile(h["symbol"]), "funding": False, "risk": RISK},
            param_space=h["space"], trial_budget=math.prod(len(v) for v in h["space"].values()))
    d = OUT / batch
    d.mkdir(parents=True, exist_ok=True)
    (d / "manifest.json").write_text(json.dumps({
        "batch": batch, "registered": time.strftime("%Y-%m-%d %H:%M UTC", time.gmtime()), "timeframe": TIMEFRAME,
        "universe": universe, "fdr_q": FDR_Q, "risk": RISK, "entries": {k: asdict(v) for k, v in T.ENTRIES.items()},
        "exits": {k: asdict(v) for k, v in T.EXITS.items()}, "filters": T.FILTERS, "horizons": T.HORIZON,
        "hypotheses": len(hs)}, indent=2) + "\n")
    reg.export()
    return hs


# ----------------------------------------------------------------------- stage 2: event study
def _screen_worker(sym: str) -> list[dict]:
    df = load([sym], TIMEFRAME, "development").frames[sym]
    return [asdict(t) for t in screen.screen_symbol((sym, df, list(T.FILTERS)))]


def event_studies(batch: str, universe, workers: int) -> list[dict]:
    path = OUT / batch / "event_studies.json"
    if path.exists():
        return json.loads(path.read_text())
    tests = []
    with ProcessPoolExecutor(workers) as ex:
        for res in ex.map(_screen_worker, universe):
            tests += res
    q = stats.bh_adjusted([t["p_value"] for t in tests])
    for t, qq in zip(tests, q):
        t["q_value"] = float(qq)
    path.write_text(json.dumps(tests, indent=1, default=float) + "\n")
    return tests


def record_effects(batch: str, reg: Registry, hs: list[dict], tests: list[dict]) -> list[dict]:
    """Write the event-study outcome to every hypothesis; return those with an effect."""
    by = {}
    for t in tests:
        by.setdefault((t["entry"], t["filt"], t["symbol"]), []).append(t)
    effects = []
    for h in hs:
        ts = by[(h["entry"], h["filter"], h["symbol"])]
        best = min(ts, key=lambda t: t["q_value"])
        h["event_q"], h["event_t"], h["event_n"] = best["q_value"], best["t_stat"], best["events"]
        if reg.hypothesis(h["id"])["status"] != "IDEA":
            if reg.hypothesis(h["id"])["status"] != "REJECTED" or best["q_value"] < FDR_Q:
                effects.append(h)
            continue
        cls = T.rule_strategy(h["entry"], h["filter"], h["exit"])
        eid = reg.start_experiment(
            hypothesis_id=h["id"], strategy_id=cls.name, strategy_version=cls().strategy_version,
            stage="event_study", market=instruments.get(h["symbol"]).asset_class, instruments=[h["symbol"]],
            timeframe=TIMEFRAME, data_split="development", data_versions={}, config={"horizon": best["horizon"]},
            notes=f"discovery {batch}: BH across {len(tests)} tests")
        for t in ts:
            reg.add_stat_test(eid, "event_study", statistic=t["t_stat"], p_value=t["p_value"],
                              passed=t["q_value"] < FDR_Q, details={"x": t["x"], "events": t["events"],
                                                                     "mean_excess": t["mean_excess"],
                                                                     "q_value": t["q_value"]})
        if best["q_value"] < FDR_Q:
            reg.finish_experiment(eid, "effect")
            reg.set_status(h["id"], "EFFECT", f"event study q={best['q_value']:.4f} (x={best['x']})", eid)
            effects.append(h)
        else:
            reg.finish_experiment(eid, "no_effect")
            reg.set_status(h["id"], "REJECTED", f"no event-study effect (best BH q={best['q_value']:.3f})", eid)
    return effects


# ----------------------------------------------------------------------- stage 3: full evaluation
def _eval_worker(h: dict, floor: int) -> dict:
    from lab.validation.evaluate import evaluate
    reg = Registry()
    try:
        cls = T.rule_strategy(h["entry"], h["filter"], h["exit"])
        t0 = time.time()
        ev = evaluate(cls, h["space"], [h["symbol"]], TIMEFRAME, hypothesis_id=h["id"], registry=reg,
                      execution=ExecutionConfig(cost_profile=cost_profile(h["symbol"])), risk=RiskConfig(**RISK),
                      export=False, n_boot=300, notes=f"discovery {h['id'].rsplit('-', 1)[0]}",
                      family_trials_floor=floor)
        d, v = ev.dev_metrics, ev.val_metrics
        return {**{k: h[k] for k in ("id", "entry", "filter", "exit", "symbol", "family", "title")},
                "verdict": ev.verdict, "confidence": ev.confidence, "best_params": ev.best_params,
                "reasons": ev.reasons, "family_trials": ev.family_trials,
                "dsr": ev.diagnostics["deflated_sharpe"]["dsr"],
                "spa_p": ev.diagnostics.get("spa", {}).get("spa_p_value"),
                "dev": {k: d.get(k) for k in ("trades", "total_return", "sharpe", "max_drawdown", "profit_factor",
                                              "win_rate", "exposure", "benchmark_total_return")},
                "val": {k: v.get(k) for k in ("trades", "total_return", "sharpe", "max_drawdown")} if v else None,
                "event_q": h["event_q"], "seconds": round(time.time() - t0, 1)}
    finally:
        reg.close()


def evaluate_effects(batch: str, effects: list[dict], hs: list[dict], workers: int) -> list[dict]:
    path = OUT / batch / "evaluations.jsonl"
    done = {}
    if path.exists():
        for line in path.read_text().splitlines():
            r = json.loads(line)
            done[r["id"]] = r
    family_size = {}
    for h in hs:
        family_size[h["family"]] = family_size.get(h["family"], 0) + math.prod(len(v) for v in h["space"].values())
    todo = [h for h in effects if h["id"] not in done]
    print(f"full evaluation: {len(todo)} to run ({len(done)} already done), {workers} workers")
    with ProcessPoolExecutor(workers) as ex, path.open("a") as f:
        futs = {ex.submit(_eval_worker, h, family_size[h["family"]]): h for h in todo}
        for i, fut in enumerate(as_completed(futs), 1):
            h = futs[fut]
            try:
                r = fut.result()
            except Exception as e:  # logged, never silently dropped
                r = {**{k: h[k] for k in ("id", "entry", "filter", "exit", "symbol", "family", "title")},
                     "verdict": "ERROR", "reasons": [repr(e)[:300]], "event_q": h["event_q"]}
            done[r["id"]] = r
            f.write(json.dumps(r, default=_num) + "\n")
            f.flush()
            print(f"[{i}/{len(todo)}] {r['id']} {r['symbol']} {r['family']}: {r['verdict']}")
    return [done[h["id"]] for h in effects if h["id"] in done]


def _num(x):
    if isinstance(x, (np.floating, np.integer)):
        return x.item()
    return str(x)


def run(batch: str, universe=UNIVERSE, workers: int | None = None) -> Path:
    workers = workers or max(1, (os.cpu_count() or 2))
    reg = Registry()
    hs = register(batch, reg, universe)
    t0 = time.time()
    tests = event_studies(batch, universe, workers)
    effects = record_effects(batch, reg, hs, tests)
    reg.export()
    print(f"event studies: {len(tests)} tests, {len(effects)}/{len(hs)} hypotheses with an effect "
          f"({time.time() - t0:.0f}s)")
    reg.close()
    results = evaluate_effects(batch, effects, hs, workers)
    reg = Registry()
    reg.export()
    from lab.discovery.report import write_report
    return write_report(batch, hs, tests, results, reg)
